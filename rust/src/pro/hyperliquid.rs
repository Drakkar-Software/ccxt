        //                     "liquidationMarkPx": null,
        //                     "tid": 567547935839686,
        //                     "cloid": null
        //                 }
        //             ]
        //         }
        //     }
        //
        let mut entry: Value = self.safe_dict(message.clone(), Value::from("data"), Value::new_object());
        if self.get("myTrades".into()).is_nullish() {
            let mut limit: Value = self.safe_integer(self.get("options".into()), Value::from("tradesLimit"), Value::from(1000));
            self.set("my_trades".into(), ArrayCacheBySymbolById::new(limit));
        };
        let mut trades: Value = self.get("myTrades".into());
        let mut symbols: Value = Value::new_object();
        let mut data: Value = self.safe_list(entry.clone(), Value::from("fills"), Value::new_array());
        let mut data_length: usize = data.len();
        if data_length.clone() == Value::from(0) {
            return Value::Undefined;
        };
        let mut i: usize = 0;
        while i < data.len() {
            let mut raw_trade: Value = data.get(i.into());
            let mut parsed: Value = <Self as Hyperliquid>::parse_ws_trade(self, raw_trade.clone(), Value::Undefined);
            let mut symbol: Value = parsed.get(Value::from("symbol"));
            symbols.set(symbol.clone(), true.into());
            trades.append(parsed.clone());
            i += 1;
        };
        let mut keys: Value = Object::keys(symbols.clone());
