    fn handle_subscription_response(&mut self, mut client: Value, mut message: Value) -> Value {
        // {
        //     "channel":"subscriptionResponse",
        //     "data":{
        //        "method":"unsubscribe",
        //        "subscription":{
        //           "type":"l2Book",
        //           "coin":"BTC",
        //           "nSigFigs":5,
        //           "mantissa":null
        //        }
        //     }
        // }
        //
        //  {
        //      "channel":"subscriptionResponse",
        //      "data":{
        //         "method":"unsubscribe",
        //         "subscription":{
        //            "type":"trades",
        //            "coin":"PURR/USDC"
        //         }
        //      }
        //  }
        //
        let mut data: Value = self.safe_dict(message.clone(), Value::from("data"), Value::new_object());
        let mut method: Value = self.safe_string(data.clone(), Value::from("method"));
        if method.clone() == Value::from("unsubscribe") {
            let mut subscription: Value = self.safe_dict(data.clone(), Value::from("subscription"), Value::new_object());
            let mut r#type: Value = self.safe_string(subscription.clone(), Value::from("type"));
            if r#type.clone() == Value::from("l2Book") {
                <Self as Hyperliquid>::handle_order_book_unsubscription(self, client.clone(), subscription.clone());
            } else if r#type.clone() == Value::from("trades") {
                <Self as Hyperliquid>::handle_trades_unsubscription(self, client.clone(), subscription.clone());
            } else if r#type.clone() == Value::from("webData2") {
                <Self as Hyperliquid>::handle_tickers_unsubscription(self, client.clone(), subscription.clone());
            } else if r#type.clone() == Value::from("candle") {
                <Self as Hyperliquid>::handle_ohlcv_unsubscription(self, client.clone(), subscription.clone());
            } else if r#type.clone() == Value::from("orderUpdates") {
                <Self as Hyperliquid>::handle_order_unsubscription(self, client.clone(), subscription.clone());
            } else if r#type.clone() == Value::from("userFills") {
                <Self as Hyperliquid>::handle_my_trades_unsubscription(self, client.clone(), subscription.clone());
            };
        };
        Value::Undefined
    }

    fn handle_message(&mut self, mut client: Value, mut message: Value) -> Value {
        //
        // {
        //     "channel":"subscriptionResponse",
        //     "data":{
        //        "method":"unsubscribe",
        //        "subscription":{
        //           "type":"l2Book",
        //           "coin":"BTC",
        //           "nSigFigs":5,
        //           "mantissa":null
        //        }
        //     }
        // }
        //
        if <Self as Hyperliquid>::handle_error_message(self, client.clone(), message.clone()).is_truthy() {
            return Value::Undefined;
        };
        let mut topic: Value = self.safe_string(message.clone(), Value::from("channel"), Value::from(""));
        let mut methods: Value = Value::Json(normalize(&Value::Json(json!({
            "pong": self.get("handlePong".into()),
            "trades": self.get("handleTrades".into()),
            "l2Book": self.get("handleOrderBook".into()),
            "candle": self.get("handleOHLCV".into()),
            "orderUpdates": self.get("handleOrder".into()),
            "userFills": self.get("handleMyTrades".into()),
            "webData2": self.get("handleWsTickers".into()),
            "allMids": self.get("handleWsTickers".into()),
            "post": self.get("handleWsPost".into()),
            "subscriptionResponse": self.get("handleSubscriptionResponse".into())
        }))).unwrap());
        let mut exac_method: Value = self.safe_value(methods.clone(), topic.clone());
        if exac_method.clone().is_nonnullish() {
            exac_method.call(self, client.clone(), message.clone());
            return Value::Undefined;
        };
        let mut keys: Value = Object::keys(methods.clone());
        let mut i: usize = 0;
        while i < keys.len() {
            let mut key: Value = keys.get(i.into());
            if topic.index_of(keys.get(i.into())) >= Value::from(0) {
                let mut method: Value = methods.get(key.clone());
                method.call(self, client.clone(), message.clone());
                return Value::Undefined;
            };
            i += 1;
        };
        Value::Undefined
    }

