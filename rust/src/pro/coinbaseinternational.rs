    fn handle_ohlcv(&mut self, mut client: Value, mut message: Value) -> Value {
        //
        // {
        //     "sequence": 0,
        //     "product_id": "BTC-PERP",
        //     "channel": "CANDLES_ONE_MINUTE",
        //     "type": "SNAPSHOT",
        //     "candles": [
        //       {
        //           "time": "2023-05-10T14:58:47.000Z",
        //           "low": "28787.8",
        //           "high": "28788.8",
        //           "open": "28788.8",
        //           "close": "28787.8",
        //           "volume": "0.466"
        //        },
        //     ]
        //  }
        //
        let mut message_hash: Value = self.safe_string(message.clone(), Value::from("channel"), Value::Undefined);
        let mut market_id: Value = self.safe_string(message.clone(), Value::from("product_id"), Value::Undefined);
        let mut market: Value = self.safe_market(market_id.clone(), Value::Undefined, Value::Undefined, Value::Undefined);
        let mut symbol: Value = market.get(Value::from("symbol"));
        let mut timeframe: Value = self.find_timeframe(message_hash.clone(), Value::Undefined);
        self.get("ohlcvs".into()).set(symbol.clone(), self.safe_value(self.get("ohlcvs".into()), symbol.clone(), Value::new_object()));
        if self.safe_value(self.get("ohlcvs".into()).get(symbol.clone()), timeframe.clone(), Value::Undefined).is_nullish() {
            let mut limit: Value = self.safe_integer(self.get("options".into()), Value::from("OHLCVLimit"), Value::from(1000));
            self.get("ohlcvs".into()).get(symbol.clone()).set(timeframe.clone(), ArrayCacheByTimestamp::new(limit));
        };
        let mut stored: Value = self.get("ohlcvs".into()).get(symbol.clone()).get(timeframe.clone());
        let mut data: Value = self.safe_list(message.clone(), Value::from("candles"), Value::new_array());
        let mut i: usize = 0;
        while i < data.len() {
            let mut tick: Value = data.get(i.into());
            let mut parsed: Value = self.parse_ohlcv(tick.clone(), market.clone());
            stored.append(parsed.clone());
            i += 1;
        };
        client.resolve(stored.clone(), message_hash.clone() + Value::from("::") + symbol.clone());
        Value::Undefined
    }

