        //             baseVolume: '9445.2043',
        //             quoteVolume: '22807159.1148',
        //             ts: 1728131730687,
        //             labeId: 0,
        //             openUtc: '2414.50',
        //             chgUTC: '0.00272',
        //             bidSz: '3.866',
        //             askSz: '0.124'
        //         }
        //     ],
        //     ts: 1728131730688
        //
        let mut arg: Value = self.safe_dict(message.clone(), Value::from("arg"), Value::new_object());
        let mut market: Value = <Self as Coincatch>::get_market_from_arg(self, arg.clone());
