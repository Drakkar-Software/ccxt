    fn handle_subject(&mut self, mut client: Value, mut message: Value) -> Value {
        //
        //     {
        //         "data": {
        //             "timestamp": "1583656800",
        //             "microtimestamp": "1583656800237527",
        //             "bids": [
        //                 ["8732.02", "0.00002478", "1207590500704256"],
        //                 ["8729.62", "0.01600000", "1207590502350849"],
        //                 ["8727.22", "0.01800000", "1207590504296448"],
        //             ],
        //             "asks": [
        //                 ["8735.67", "2.00000000", "1207590693249024"],
        //                 ["8735.67", "0.01700000", "1207590693634048"],
        //                 ["8735.68", "1.53294500", "1207590692048896"],
        //             ],
        //         },
        //         "event": "data",
        //         "channel": "detail_order_book_btcusd"
        //     }
        //
        // private order
        //     {
        //         "data":{
        //         "id":"1463471322288128",
        //         "id_str":"1463471322288128",
        //         "order_type":1,
        //         "datetime":"1646127778",
        //         "microtimestamp":"1646127777950000",
        //         "amount":0.05,
        //         "amount_str":"0.05000000",
        //         "price":1000,
        //         "price_str":"1000.00"
        //         },
        //         "channel":"private-my_orders_ltcusd-4848701",
        //         "event": "order_deleted" // field only present for cancelOrder
        //     }
        //
        let mut channel: Value = self.safe_string(message.clone(), Value::from("channel"), Value::Undefined);
        let mut methods: Value = Value::Json(normalize(&Value::Json(json!({
            "live_trades": self.get("handleTrade".into()),
            "diff_order_book": self.get("handleOrderBook".into()),
            "private-my_orders": self.get("handleOrders".into())
        }))).unwrap());
        let mut keys: Value = methods.clone().keys();
        let mut i: usize = 0;
        while i < keys.len() {
            let mut key: Value = keys.get(i.into());
            if channel.index_of(key.clone()) > Value::from(1).neg() {
                let mut method: Value = methods.get(key.clone());
                method.call(self, client.clone(), message.clone());
            };
            i += 1;
        };
        Value::Undefined
    }

    fn handle_error_message(&mut self, mut client: Value, mut message: Value) -> Value {
        // {
        //     "event": "bts:error",
        //     "channel": '',
        //     "data": { code: 4009, message: "Connection is unauthorized." }
        // }
        let mut event: Value = self.safe_string(message.clone(), Value::from("event"), Value::Undefined);
        if event.clone() == Value::from("bts:error") {
            let mut feedback: Value = self.get("id".into()) + Value::from(" ") + self.json(message.clone());
            let mut data: Value = self.safe_value(message.clone(), Value::from("data"), Value::new_object());
            let mut code: Value = self.safe_number(data.clone(), Value::from("code"), Value::Undefined);
            self.throw_exactly_matched_exception(self.get("exceptions".into()).get(Value::from("exact")), code.clone(), feedback.clone());
        };
        return true.into();
    }

