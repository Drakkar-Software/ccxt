        if symbols_length.clone() == Value::from(0) {
            panic!(r###"BadRequest::new(self.get("id".into()) + Value::from(" watchOrderBookForSymbols() requires a non-empty array of symbols"))"###);
        };
        let mut name: Value = Value::from("level2");
        self.load_markets(Value::Undefined, Value::Undefined).await;
        symbols = self.market_symbols(symbols.clone(), Value::Undefined, Value::Undefined, Value::Undefined, Value::Undefined);
        let mut market_ids: Value = self.market_ids(symbols.clone());
        let mut message_hashes: Value = Value::new_array();
        let mut i: usize = 0;
        while i < symbols_length.clone().into() {
            let mut market_id: Value = market_ids.get(i.into());
            message_hashes.push(name.clone() + Value::from(":") + market_id.clone());
            i += 1;
        };
