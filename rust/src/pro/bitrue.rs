    fn parse_ws_balances(&self, mut balances: Value) -> Value {
        //
        //    [{
        //         "a": "btc",
        //         "F": "0.0006000000000000",
        //         "T": 1657799510000,
        //         "f": "0.0006000000000000",
        //         "t": 0
        //     },
        //     {
        //         "a": "usdt",
        //         "T": 0,
        //         "L": "0.0000000000000000",
        //         "l": "-11.8705317318000000",
        //         "t": 1657799510000
        //     }]
        //
        self.get("balance".into()).set("info".into(), balances.clone());
        let mut i: usize = 0;
        while i < balances.len() {
            let mut balance: Value = balances.get(i.into());
            let mut currency_id: Value = self.safe_string(balance.clone(), Value::from("a"), Value::Undefined);
            let mut code: Value = self.safe_currency_code(currency_id.clone(), Value::Undefined);
            let mut account: Value = self.account();
            let mut free: Value = self.safe_string(balance.clone(), Value::from("F"), Value::Undefined);
            let mut used: Value = self.safe_string(balance.clone(), Value::from("L"), Value::Undefined);
            let mut balance_update_time: Value = self.safe_integer(balance.clone(), Value::from("T"), Value::from(0));
            let mut lock_balance_update_time: Value = self.safe_integer(balance.clone(), Value::from("t"), Value::from(0));
            let mut update_free: Value = (balance_update_time.clone() != Value::from(0)).into();
            let mut update_used: Value = (lock_balance_update_time.clone() != Value::from(0)).into();
            if update_free.is_truthy() || update_used.is_truthy() {
                if update_free.is_truthy() {
                    account.set("free".into(), free.clone());
                };
                if update_used.is_truthy() {
                    account.set("used".into(), used.clone());
                };
                self.get("balance".into()).set(code.clone(), account.clone());
            };
            i += 1;
        };
        self.set("balance".into(), self.safe_balance(self.get("balance".into())));
        Value::Undefined
    }

