    fn request_id(&mut self) -> Value {
        self.lock_id();
        let mut request_id: Value = self.sum(self.safe_integer(self.get("options".into()), Value::from("requestId"), Value::from(0)), Value::from(1));
        self.get("options".into()).set("requestId".into(), request_id.clone());
        self.unlock_id();
        return request_id.clone();
    }

    async fn subscribe(&mut self, mut url: Value, mut message_hash: Value, mut subscription_hash: Value, mut params: Value, mut subscription: Value) -> Value {
        params = params.or_default(Value::new_object());
        let mut request_id: Value = <Self as Kucoin>::request_id(self).to_string();
        let mut request: Value = Value::Json(normalize(&Value::Json(json!({
            "id": request_id,
            "type": "subscribe",
            "topic": subscription_hash,
            "response": true
        }))).unwrap());
        let mut message: Value = extend_2(request.clone(), params.clone());
        let mut client: Value = self.client(url.clone());
        if !client.get(subscriptions.clone()).contains_key(subscription_hash.clone()) {
            client.get(subscriptions.clone()).set(request_id.clone(), subscription_hash.clone());
        };
        return self.watch(url.clone(), message_hash.clone(), message.clone(), subscription_hash.clone(), subscription.clone()).await;
    }

    async fn un_subscribe(&mut self, mut url: Value, mut message_hash: Value, mut topic: Value, mut subscription_hash: Value, mut params: Value, mut subscription: Value) -> Value {
        params = params.or_default(Value::new_object());
        return <Self as Kucoin>::un_subscribe_multiple(self, url.clone(), Value::Json(serde_json::Value::Array(vec![message_hash.clone().into()])), topic.clone(), Value::Json(serde_json::Value::Array(vec![subscription_hash.clone().into()])), params.clone(), subscription.clone()).await;
    }

    async fn subscribe_multiple(&mut self, mut url: Value, mut message_hashes: Value, mut topic: Value, mut subscription_hashes: Value, mut params: Value, mut subscription: Value) -> Value {
        params = params.or_default(Value::new_object());
        let mut request_id: Value = <Self as Kucoin>::request_id(self).to_string();
        let mut request: Value = Value::Json(normalize(&Value::Json(json!({
            "id": request_id,
            "type": "subscribe",
            "topic": topic,
            "response": true
        }))).unwrap());
        let mut message: Value = extend_2(request.clone(), params.clone());
        let mut client: Value = self.client(url.clone());
        let mut i: usize = 0;
        while i < subscription_hashes.len() {
            let mut subscription_hash: Value = subscription_hashes.get(i.into());
            if !client.get(subscriptions.clone()).contains_key(subscription_hash.clone()) {
                client.get(subscriptions.clone()).set(request_id.clone(), subscription_hash.clone());
            };
            i += 1;
        };
        return self.watch_multiple(url.clone(), message_hashes.clone(), message.clone(), subscription_hashes.clone(), subscription.clone()).await;
    }

    async fn un_subscribe_multiple(&mut self, mut url: Value, mut message_hashes: Value, mut topic: Value, mut subscription_hashes: Value, mut params: Value, mut subscription: Value) -> Value {
        params = params.or_default(Value::new_object());
        let mut request_id: Value = <Self as Kucoin>::request_id(self).to_string();
        let mut request: Value = Value::Json(normalize(&Value::Json(json!({
            "id": request_id,
            "type": "unsubscribe",
            "topic": topic,
            "response": true
        }))).unwrap());
        let mut message: Value = extend_2(request.clone(), params.clone());
        if subscription.clone().is_nonnullish() {
            subscription.set(request_id.clone(), request_id.clone());
        };
        let mut client: Value = self.client(url.clone());
        let mut i: usize = 0;
        while i < subscription_hashes.len() {
            let mut subscription_hash: Value = subscription_hashes.get(i.into());
            if !client.get(subscriptions.clone()).contains_key(subscription_hash.clone()) {
                client.get(subscriptions.clone()).set(request_id.clone(), subscription_hash.clone());
            };
            i += 1;
        };
        return self.watch_multiple(url.clone(), message_hashes.clone(), message.clone(), subscription_hashes.clone(), subscription.clone()).await;
    }

    async fn watch_ticker(&mut self, mut symbol: Value, mut params: Value) -> Value {
        params = params.or_default(Value::new_object());
        self.load_markets(Value::Undefined, Value::Undefined).await;
        let mut market: Value = self.market(symbol.clone());
        symbol = market.get(Value::from("symbol"));
        let mut url: Value = <Self as Kucoin>::negotiate(self, false.into()).await;
        let (mut method, mut query) = shift_2(self.handle_option_and_params(params.clone(), Value::from("watchTicker"), Value::from("method"), Value::from("/market/snapshot")));
        let mut topic: Value = method.clone() + Value::from(":") + market.get(Value::from("id"));
        let mut message_hash: Value = Value::from("ticker:") + symbol.clone();
        return <Self as Kucoin>::subscribe(self, url.clone(), message_hash.clone(), topic.clone(), query.clone()).await;
    }

