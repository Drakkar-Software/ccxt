    async fn authenticate(&mut self, mut params: Value) -> Value {
        params = params.or_default(Value::new_object());
        self.check_required_credentials(Value::Undefined);
        let mut expires: Value = self.milliseconds() + self.safe_integer(self.get("options".into()), Value::from("requestExpiration"), Value::from(5000)) * Value::from(1000);
        // need macroseconds
        let mut ws_options: Value = self.safe_dict(self.get("options".into()), Value::from("ws"), Value::new_object());
        let mut authenticated: Value = self.safe_string(ws_options.clone(), Value::from("token"), Value::Undefined);
        if authenticated.clone().is_nullish() {
            let mut method: Value = Value::from("GET");
            let mut body_str: Value = Value::from("");
            let mut path: Value = Value::from("ws");
            let mut payload: Value = self.get("apiKey".into()) + expires.to_string() + method.to_upper_case() + Value::from("/") + path.clone() + body_str.clone();
            let mut decoded_secret: Value = self.base64_to_binary(self.get("secret".into()));
            let mut signature: Value = self.hmac(self.encode(payload.clone()), decoded_secret.clone(), sha256.clone(), Value::from("base64"));
            let mut default_options: Value = Value::Json(normalize(&Value::Json(json!({
                "ws": Value::Json(normalize(&Value::Json(json!({
                    "options": Value::Json(normalize(&Value::Json(json!({
                        "headers": Value::Json(normalize(&Value::Json(json!({
                            "Content-Type": "application/json",
                            "Accept": "application/json",
                            "Arkham-Api-Key": self.get("apiKey".into()),
                            "Arkham-Expires": expires.to_string(),
                            "Arkham-Signature": signature
                        }))).unwrap())
                    }))).unwrap())
                }))).unwrap())
            }))).unwrap());
            self.extend_exchange_options(default_options.clone());
            self.client(self.get("urls".into()).get(Value::from("api")).get(Value::from("ws")));
        };
        Value::Undefined
    }

