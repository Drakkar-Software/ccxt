    fn handle_positions(&mut self, mut client: Value, mut message: Value) -> Value {
        //
        // snapshot:
        //
        //     {
        //         channel: 'positions',
        //         type: 'snapshot',
        //         data: [
        //           {
        //             subaccountId: 0,
        //             symbol: 'SOL_USDT_PERP',
        //             base: '0.059',
        //             quote: '-11.50618',
        //             openBuySize: '0',
        //             openSellSize: '0',
        //             openBuyNotional: '0',
        //             openSellNotional: '0',
        //             lastUpdateReason: 'orderFill',
        //             lastUpdateTime: '1755251065621402',
        //             lastUpdateId: 2709589783,
        //             lastUpdateBaseDelta: '0.059',
        //             lastUpdateQuoteDelta: '-11.50618',
        //             breakEvenPrice: '195.02',
        //             markPrice: '195',
        //             value: '11.505',
        //             pnl: '-0.00118',
        //             initialMargin: '1.1505',
        //             maintenanceMargin: '0.6903',
        //             averageEntryPrice: '195.02'
        //           }
        //         ]
        //     }
        //
        let mut new_positions: Value = Value::new_array();
        if self.get("positions".into()).is_nullish() {
            self.set("positions".into(), Value::new_object());
        };
        let mut r#type: Value = self.safe_string(message.clone(), Value::from("type"), Value::Undefined);
        if r#type.clone() == Value::from("snapshot") {
            let mut data: Value = self.safe_list(message.clone(), Value::from("data"), Value::new_array());
            let mut i: usize = 0;
            while i < data.len() {
                let mut position: Value = <Self as Arkham>::parse_ws_position(self, data.get(i.into()));
                if self.safe_integer(position.clone(), Value::from("entryPrice"), Value::Undefined) != Value::from(0) {
                    new_positions.push(position.clone());
                    let mut symbol: Value = self.safe_string(position.clone(), Value::from("symbol"), Value::Undefined);
                    self.get("positions".into()).set(symbol.clone(), position.clone());
                };
                i += 1;
            };
        } else {
            let mut data: Value = self.safe_dict(message.clone(), Value::from("data"), Value::Undefined);
            let mut position: Value = <Self as Arkham>::parse_ws_position(self, data.clone());
            let mut symbol: Value = self.safe_string(position.clone(), Value::from("symbol"), Value::Undefined);
            self.get("positions".into()).set(symbol.clone(), position.clone());
            new_positions.push(position.clone());
        };
        let mut message_hashes: Value = self.find_message_hashes(client.clone(), Value::from("positions::"));
        let mut i: usize = 0;
        while i < message_hashes.len() {
            let mut message_hash: Value = message_hashes.get(i.into());
            let mut parts: Value = message_hash.split(Value::from("::"));
            let mut symbols_string: Value = parts.get(Value::from(1));
            let mut symbols: Value = symbols_string.split(Value::from(","));
            let mut positions: Value = self.filter_by_array(new_positions.clone(), Value::from("symbol"), symbols.clone(), false.into());
            if !self.is_empty(positions.clone()).is_truthy() {
                client.resolve(positions.clone(), message_hash.clone());
            };
            i += 1;
        };
        let mut length: usize = new_positions.len();
        if length > 0 {
            client.resolve(new_positions.clone(), Value::from("positions"));
        };
        Value::Undefined
    }

