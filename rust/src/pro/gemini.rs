    fn handle_message(&mut self, mut client: Value, mut message: Value) -> Value {
        //
        //  public
        //     {
        //         "type": "trade",
        //         "symbol": "BTCUSD",
        //         "event_id": 122278173770,
        //         "timestamp": 1655335880981,
        //         "price": "22530.80",
        //         "quantity": "0.04",
        //         "side": "buy"
        //     }
        //
        //  private
        //     [
        //         {
        //             "type": "accepted",
        //             "order_id": "134150423884",
        //             "event_id": "134150423886",
        //             "account_name": "primary",
        //             "client_order_id": "1659739406916",
        //             "api_session": "account-pnBFSS0XKGvDamX4uEIt",
        //             "symbol": "batbtc",
        //             "side": "sell",
        //             "order_type": "exchange limit",
        //             "timestamp": "1659739407",
        //             "timestampms": 1659739407576,
        //             "is_live": true,
        //             "is_cancelled": false,
        //             "is_hidden": false,
        //             "original_amount": "1",
        //             "price": "1",
        //             "socket_sequence": 139
        //         }
        //     ]
        //
        let mut is_array: Value = Array::is_array(message.clone());
        if is_array.is_truthy() {
            <Self as Gemini>::handle_order(self, client.clone(), message.clone());
            return Value::Undefined;
        };
        let mut reason: Value = self.safe_string(message.clone(), Value::from("reason"), Value::Undefined);
        if reason.clone() == Value::from("error") {
            <Self as Gemini>::handle_error(self, client.clone(), message.clone());
        };
        let mut methods: Value = Value::Json(normalize(&Value::Json(json!({
            "l2_updates": self.get("handleL2Updates".into()),
            "trade": self.get("handleTrade".into()),
            "subscription_ack": self.get("handleSubscription".into()),
            "heartbeat": self.get("handleHeartbeat".into())
        }))).unwrap());
        let mut r#type: Value = self.safe_string(message.clone(), Value::from("type"), Value::from(""));
        if r#type.index_of(Value::from("candles")) >= Value::from(0) {
            <Self as Gemini>::handle_ohlcv(self, client.clone(), message.clone());
            return Value::Undefined;
        };
        let mut method: Value = self.safe_value(methods.clone(), r#type.clone(), Value::Undefined);
        if method.clone().is_nonnullish() {
            method.call(self, client.clone(), message.clone());
        };
        // handle multimarketdata
        if r#type.clone() == Value::from("update") {
            let mut ts: Value = self.safe_integer(message.clone(), Value::from("timestampms"), self.milliseconds());
            let mut event_id: Value = self.safe_integer(message.clone(), Value::from("eventId"), Value::Undefined);
            let mut events: Value = self.safe_list(message.clone(), Value::from("events"), Value::Undefined);
            let mut order_book_items: Value = Value::new_array();
            let mut bidask_items: Value = Value::new_array();
            let mut collected_events_of_trades: Value = Value::new_array();
            let mut events_length: usize = events.len();
            let mut i: usize = 0;
            while i < events.len() {
                let mut event: Value = events.get(i.into());
                let mut event_type: Value = self.safe_string(event.clone(), Value::from("type"), Value::Undefined);
                let mut is_order_book: Value = (event_type.clone() == Value::from("change") && event.contains_key(Value::from("side")) && self.in_array(event.get(Value::from("side")), Value::Json(serde_json::Value::Array(vec![Value::from("ask").into(), Value::from("bid").into()]))).is_truthy()).into();
                let mut event_reason: Value = self.safe_string(event.clone(), Value::from("reason"), Value::Undefined);
                let mut is_bid_ask: Value = (event_reason.clone() == Value::from("top-of-book") || is_order_book.is_truthy() && event_reason.clone() == Value::from("initial") && events_length.clone() == Value::from(2)).into();
                if is_bid_ask.is_truthy() {
                    bidask_items.push(event.clone());
                } else if is_order_book.is_truthy() {
                    order_book_items.push(event.clone());
                } else if event_type.clone() == Value::from("trade") {
                    collected_events_of_trades.push(events.get(i.into()));
                };
                i += 1;
            };
            let mut length_ba: usize = bidask_items.len();
            if length_ba.clone() > Value::from(0) {
                <Self as Gemini>::handle_bids_asks_for_multidata(self, client.clone(), bidask_items.clone(), ts.clone(), event_id.clone());
            };
            let mut length_ob: usize = order_book_items.len();
            if length_ob.clone() > Value::from(0) {
                <Self as Gemini>::handle_order_book_for_multidata(self, client.clone(), order_book_items.clone(), ts.clone(), event_id.clone());
            };
            let mut length_trades: usize = collected_events_of_trades.len();
            if length_trades.clone() > Value::from(0) {
                <Self as Gemini>::handle_trades_for_multidata(self, client.clone(), collected_events_of_trades.clone(), ts.clone());
            };
        };
        Value::Undefined
    }

    async fn authenticate(&mut self, mut params: Value) -> Value {
        params = params.or_default(Value::new_object());
        let mut url: Value = self.safe_string(params.clone(), Value::from("url"), Value::Undefined);
        if self.get("clients".into()).is_nonnullish() && self.get("clients".into()).contains_key(url.clone()) {
            return Value::Undefined;
        };
        self.check_required_credentials(Value::Undefined);
        let mut start_index: usize = self.get("urls".into()).get(Value::from("api")).get(Value::from("ws")).len();
        let mut url_params_index: Value = url.index_of(Value::from("?"));
        let mut url_length: usize = url.len();
        let mut end_index: Value = if url_params_index.clone() >= Value::from(0) { url_params_index.clone() } else { url_length.clone() };
        let mut request: Value = url.slice(start_index.clone(), end_index.clone());
        let mut payload: Value = Value::Json(normalize(&Value::Json(json!({
            "request": request,
            "nonce": self.nonce()
        }))).unwrap());
        let mut b64: Value = self.string_to_base64(self.json(payload.clone()));
        let mut signature: Value = self.hmac(self.encode(b64.clone()), self.encode(self.get("secret".into())), sha384.clone(), Value::from("hex"));
        let mut default_options: Value = Value::Json(normalize(&Value::Json(json!({
            "ws": Value::Json(normalize(&Value::Json(json!({
                "options": Value::Json(normalize(&Value::Json(json!({
                    "headers": Value::new_object()
                }))).unwrap())
            }))).unwrap())
        }))).unwrap());
        // this.options = this.extend (defaultOptions, this.options);
        self.extend_exchange_options(default_options.clone());
        let mut original_headers: Value = self.get("options".into()).get(Value::from("ws")).get(Value::from("options")).get(Value::from("headers"));
        let mut headers: Value = Value::Json(normalize(&Value::Json(json!({
            "X-GEMINI-APIKEY": self.get("apiKey".into()),
            "X-GEMINI-PAYLOAD": b64,
            "X-GEMINI-SIGNATURE": signature
        }))).unwrap());
        self.get("options".into()).get(Value::from("ws")).get(Value::from("options")).set("headers".into(), headers.clone());
        self.client(url.clone());
        self.get("options".into()).get(Value::from("ws")).get(Value::from("options")).set("headers".into(), original_headers.clone());
        Value::Undefined
    }

    
