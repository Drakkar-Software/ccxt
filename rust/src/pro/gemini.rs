    fn handle_order_book(&mut self, mut client: Value, mut message: Value) -> Value {
        let mut changes: Value = self.safe_value(message.clone(), Value::from("changes"), Value::new_array());
        let mut market_id: Value = self.safe_string_lower(message.clone(), Value::from("symbol"), Value::Undefined);
        let mut market: Value = self.safe_market(market_id.clone(), Value::Undefined, Value::Undefined, Value::Undefined);
        let mut symbol: Value = market.get(Value::from("symbol"));
        let mut message_hash: Value = Value::from("orderbook:") + symbol.clone();
        // let orderbook = this.safeValue (this.orderbooks, symbol);
        if !self.get("orderbooks".into()).contains_key(symbol.clone()) {
            self.get("orderbooks".into()).set(symbol.clone(), self.order_book(Value::Undefined, Value::Undefined));
        };
        let mut orderbook: Value = self.get("orderbooks".into()).get(symbol.clone());
        let mut i: usize = 0;
        while i < changes.len() {
            let mut delta: Value = changes.get(i.into());
            let mut price: Value = self.safe_number(delta.clone(), Value::from(1), Value::Undefined);
            let mut size: Value = self.safe_number(delta.clone(), Value::from(2), Value::Undefined);
            let mut side: Value = if delta.get(Value::from(0)) == Value::from("buy") { Value::from("bids") } else { Value::from("asks") };
            let mut bookside: Value = orderbook.get(side.clone());
            bookside.store(price.clone(), size.clone());
            orderbook.set(side.clone(), bookside.clone());
            i += 1;
        };
        orderbook.set("symbol".into(), symbol.clone());
        self.get("orderbooks".into()).set(symbol.clone(), orderbook.clone());
        client.resolve(orderbook.clone(), message_hash.clone());
        Value::Undefined
    }

