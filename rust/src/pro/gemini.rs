    fn handle_ohlcv(&mut self, mut client: Value, mut message: Value) -> Value {
        //
        //     {
        //         "type": "candles_15m_updates",
        //         "symbol": "BTCUSD",
        //         "changes": [
        //             [
        //                 1561054500000,
        //                 9350.18,
        //                 9358.35,
        //                 9350.18,
        //                 9355.51,
        //                 2.07
        //             ],
        //             [
        //                 1561053600000,
        //                 9357.33,
        //                 9357.33,
        //                 9350.18,
        //                 9350.18,
        //                 1.5900161
        //             ]
        //             ...
        //         ]
        //     }
        //
        let mut r#type: Value = self.safe_string(message.clone(), Value::from("type"), Value::from(""));
        let mut timeframe_id: Value = r#type.slice(Value::from(8));
        let mut timeframe_end_index: Value = timeframe_id.index_of(Value::from("_"));
        timeframe_id = timeframe_id.slice(Value::from(0), timeframe_end_index.clone());
        let mut market_id: Value = self.safe_string(message.clone(), Value::from("symbol"), Value::from("")).to_lower_case();
        let mut market: Value = self.safe_market(market_id.clone(), Value::Undefined, Value::Undefined, Value::Undefined);
        let mut symbol: Value = self.safe_symbol(market_id.clone(), market.clone(), Value::Undefined, Value::Undefined);
        let mut changes: Value = self.safe_value(message.clone(), Value::from("changes"), Value::new_array());
        let mut timeframe: Value = self.find_timeframe(timeframe_id.clone(), Value::Undefined);
        let mut ohlcvs_by_symbol: Value = self.safe_value(self.get("ohlcvs".into()), symbol.clone(), Value::Undefined);
        if ohlcvs_by_symbol.clone().is_nullish() {
            self.get("ohlcvs".into()).set(symbol.clone(), Value::new_object());
        };
        let mut stored: Value = self.safe_value(self.get("ohlcvs".into()).get(symbol.clone()), timeframe.clone(), Value::Undefined);
        if stored.clone().is_nullish() {
            let mut limit: Value = self.safe_integer(self.get("options".into()), Value::from("OHLCVLimit"), Value::from(1000));
            stored = ArrayCacheByTimestamp::new(limit);
            self.get("ohlcvs".into()).get(symbol.clone()).set(timeframe.clone(), stored.clone());
        };
        let mut changes_length: usize = changes.len();
        // reverse order of array to store candles in ascending order
        let mut i: usize = 0;
        while i < changes_length.clone().into() {
            let mut index: Value = changes_length.clone() - Value::from(i) - Value::from(1);
            let mut parsed: Value = self.parse_ohlcv(changes.get(index.clone()), market.clone());
            stored.append(parsed.clone());
            i += 1;
        };
        let mut message_hash: Value = Value::from("ohlcv:") + symbol.clone() + Value::from(":") + timeframe_id.clone();
        client.resolve(stored.clone(), message_hash.clone());
        return message.clone();
    }

