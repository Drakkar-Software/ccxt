    async fn fetch_ohlcv(&mut self, mut symbol: Value, mut timeframe: Value, mut since: Value, mut limit: Value, mut params: Value) -> Value {
        fn collect_routes(node: &serde_json::Value, api_name: &str, out: &mut Vec<(String, String, String)>) {
            if let serde_json::Value::Object(map) = node {
                for (k, v) in map { let kl = k.to_lowercase(); if kl == "get" || kl == "post" || kl == "put" || kl == "delete" { if let serde_json::Value::Object(paths) = v { for (p, _cost) in paths { out.push((api_name.to_string(), kl.to_uppercase(), p.clone())); } } } else { collect_routes(v, api_name, out); } }
            }
        }
        let mut request = if params.is_object() { params.clone() } else { Value::new_object() };
        request.set("symbol".into(), symbol.clone());
        request.set("timeframe".into(), timeframe.clone());
        request.set("interval".into(), timeframe.clone());
        if since.is_nonnullish() { request.set("since".into(), since.clone()); request.set("startTime".into(), since.clone()); }
        if limit.is_nonnullish() { request.set("limit".into(), limit.clone()); }
        let mut dynamic_calls: Vec<(String, String, String)> = vec![];
        if let Value::Json(serde_json::Value::Object(api_map)) = <Self as Btcturk>::describe(self).get("api".into()) {
            for (api_name, node) in api_map { collect_routes(&node, &api_name, &mut dynamic_calls); }
        }
        for token in ["klines", "candles", "ohlcv"] {
            for (api_name, method_name, path_name) in &dynamic_calls {
                if method_name.as_str() != "GET" || path_name.contains('{') { continue; }
                let p = path_name.to_lowercase();
                if p == token || p.contains(token) {
                    let rv = self.request(path_name.clone().into(), api_name.clone().into(), method_name.clone().into(), request.clone(), Value::Undefined, Value::Undefined, Value::Undefined).await;
                    if !rv.is_undefined() { return rv; }
                }
            }
        }
        let candidates = vec![("public", "GET", "klines"), ("public", "GET", "candles"), ("public", "GET", "ohlcv")];
        for (api_name, method_name, path_name) in candidates {
            let rv = self.request(path_name.into(), api_name.into(), method_name.into(), request.clone(), Value::Undefined, Value::Undefined, Value::Undefined).await;
            if !rv.is_undefined() { return rv; }
        }
        Value::Undefined
    }


    fn parse_ohlcvs(&self, mut ohlcvs: Value, mut market: Value, mut timeframe: Value, mut since: Value, mut limit: Value, mut tail: Value) -> Value {
        timeframe = timeframe.or_default(Value::from("1m"));
        tail = tail.or_default(false.into());
        let mut results: Value = Value::new_array();
        let mut timestamp: Value = self.safe_list(ohlcvs.clone(), Value::from("t"), Value::new_array());
        let mut high: Value = self.safe_list(ohlcvs.clone(), Value::from("h"), Value::new_array());
        let mut open: Value = self.safe_list(ohlcvs.clone(), Value::from("o"), Value::new_array());
        let mut low: Value = self.safe_list(ohlcvs.clone(), Value::from("l"), Value::new_array());
        let mut close: Value = self.safe_list(ohlcvs.clone(), Value::from("c"), Value::new_array());
        let mut volume: Value = self.safe_list(ohlcvs.clone(), Value::from("v"), Value::new_array());
        let mut i: usize = 0;
        while i < timestamp.len() {
            let mut ohlcv: Value = Value::Json(normalize(&Value::Json(json!({
                "timestamp": self.safe_integer(timestamp.clone(), Value::from(i), Value::Undefined),
                "high": self.safe_number(high.clone(), Value::from(i), Value::Undefined),
                "open": self.safe_number(open.clone(), Value::from(i), Value::Undefined),
                "low": self.safe_number(low.clone(), Value::from(i), Value::Undefined),
                "close": self.safe_number(close.clone(), Value::from(i), Value::Undefined),
                "volume": self.safe_number(volume.clone(), Value::from(i), Value::Undefined)
            }))).unwrap());
            results.push(<Self as Btcturk>::parse_ohlcv(self, ohlcv.clone(), market.clone()));
            i += 1;
        };
        let mut sorted: Value = self.sort_by(results.clone(), Value::from(0), Value::Undefined, Value::Undefined);
        return self.filter_by_since_limit(sorted.clone(), since.clone(), limit.clone(), Value::from(0), tail.clone());
    }

