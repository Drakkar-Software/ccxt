    fn parse_cancel_orders(&self, mut orders: Value) -> Value {
        //
        //    {
        //        "success": [
        //            "5983466"
        //        ],
        //        "failed": [
        //            {
        //                "err-msg": "Incorrect order state",
        //                "order-state": 7,
        //                "order-id": "",
        //                "err-code": "order-orderstate-error",
        //                "client-order-id": "first"
        //            },
        //            ...
        //        ]
        //    }
        //
        //    {
        //        "errors": [
        //            {
        //                "order_id": "769206471845261312",
        //                "err_code": 1061,
        //                "err_msg": "This order doesnt exist."
        //            }
        //        ],
        //        "successes": "1258075374411399168,1258075393254871040"
        //    }
        //
        let mut successes: Value = self.safe_string(orders.clone(), Value::from("successes"), Value::Undefined);
        let mut success: Value = Value::Undefined;
        if successes.clone().is_nonnullish() {
            success = successes.split(Value::from(","));
        } else {
            success = self.safe_list(orders.clone(), Value::from("success"), Value::new_array());
        };
        let mut failed: Value = self.safe_list_2(orders.clone(), Value::from("errors"), Value::from("failed"), Value::new_array());
        let mut result: Value = Value::new_array();
        let mut i: usize = 0;
        while i < success.len() {
            let mut order: Value = success.get(i.into());
            result.push(self.safe_order(Value::Json(normalize(&Value::Json(json!({
                "info": order,
                "id": order,
                "status": "canceled"
            }))).unwrap()), Value::Undefined));
            i += 1;
        };
        let mut i: usize = 0;
        while i < failed.len() {
            let mut order: Value = failed.get(i.into());
            result.push(self.safe_order(Value::Json(normalize(&Value::Json(json!({
                "info": order,
                "id": self.safe_string_2(order.clone(), Value::from("order-id"), Value::from("order_id"), Value::Undefined),
                "status": "failed",
                "clientOrderId": self.safe_string(order.clone(), Value::from("client-order-id"), Value::Undefined)
            }))).unwrap()), Value::Undefined));
            i += 1;
        };
        return result.clone();
    }

