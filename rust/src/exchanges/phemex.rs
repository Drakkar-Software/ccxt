        //        }
        //    }
        //
        let mut data: Value = self.safe_value(response.clone(), Value::from("data"), Value::new_object());
        let mut rates: Value = self.safe_value(data.clone(), Value::from("rows"), Value::Undefined);
        let mut result: Value = Value::new_array();
