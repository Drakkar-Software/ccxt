    fn fetch_ohlcv_request(&mut self, mut symbol: Value, mut timeframe: Value, mut since: Value, mut limit: Value, mut params: Value) -> Value {
        timeframe = timeframe.or_default(Value::from("1m"));
        params = params.or_default(Value::new_object());
        let mut market: Value = self.market(symbol.clone());
        let mut request: Value = Value::Json(normalize(&Value::Json(json!({
            "market": market.get(Value::from("id")),
            "interval": self.safe_string(self.get("timeframes".into()), timeframe.clone(), timeframe.clone())
        }))).unwrap());
        // "limit": 1440, // default 1440, max 1440
        // "start": since,
        // "end": this.milliseconds (),
        if since.clone().is_nonnullish() {
            // https://github.com/ccxt/ccxt/issues/9227
            let mut duration: Value = self.parse_timeframe(timeframe.clone());
            request.set("start".into(), since.clone());
            if limit.clone().is_nullish() {
                limit = Value::from(1440);
            } else {
                limit = Math::min(limit.clone(), Value::from(1440));
            };
            request.set("end".into(), self.sum(since.clone(), limit.clone() * duration.clone() * Value::from(1000)));
        };
        (request, params) = shift_2(self.handle_until_option(Value::from("end"), request.clone(), params.clone(), Value::Undefined));
        if limit.clone().is_nonnullish() {
            request.set("limit".into(), limit.clone());
        };
        // default 1440, max 1440
        return extend_2(request.clone(), params.clone());
    }

