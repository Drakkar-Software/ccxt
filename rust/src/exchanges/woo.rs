        let mut ob = crate::exchange::unwrap_response_order_book(&json_resp);
        if let serde_json::Value::Object(ref mut map) = ob {
            if !map.contains_key("symbol") { map.insert("symbol".to_string(), serde_json::json!(symbol.unwrap_str())); }
        }
