    fn parse_order(&mut self, mut order: Value, mut market: Value) -> Value {
        //
        // fetchOrders, fetchOpenOrders, fetchClosedOrders, fetchCanceledOrders
        //
        //     {
        //         "order_id": "14",
        //         "created": "1435517311",
        //         "type": "buy",
        //         "pair": "BTC_USD",
        //         "price": "100",
        //         "quantity": "1",
        //         "amount": "100"
        //     }
        //
        // fetchOrder
        //
        //     {
        //         "type": "buy",
        //         "in_currency": "BTC",
        //         "in_amount": "1",
        //         "out_currency": "USD",
        //         "out_amount": "100",
        //         "trades": [
        //             {
        //                 "trade_id": 3,
        //                 "date": 1435488248,
        //                 "type": "buy",
        //                 "pair": "BTC_USD",
        //                 "order_id": 12345,
        //                 "quantity": 1,
        //                 "price": 100,
        //                 "amount": 100
        //             }
        //         ]
        //     }
        //
        // Margin fetchOpenOrders
        //
        //    {
        //        "client_id": "0",
        //        "comment": "",
        //        "created": "1619068707985325495",
        //        "distance": "0",
        //        "expire": 0,
        //        "funding_currency": "BTC",
        //        "funding_quantity": "0.01",
        //        "funding_rate": "0.02",
        //        "leverage": "2",
        //        "order_id": "123",
        //        "pair": "BTC_USD",
        //        "previous_type": "limit_sell",
        //        "price": "58000",
        //        "quantity": "0.01",
        //        "src": 0,
        //        "stop_price": "0",
        //        "trigger_price": "58000",
        //        "type": "limit_sell",
        //        "updated": 1619068707989411800
        //    }
        //
        // Margin fetchClosedOrders
        //
        //    {
        //        "distance": "0",
        //        "event_id": "692842802860022508",
        //        "event_time": "1619069531190173720",
        //        "event_type": "OrderCancelStarted",
        //        "order_id": "123",
        //        "order_status": "cancel_started",
        //        "order_type": "limit_sell",
        //        "pair": "BTC_USD",
        //        "price": "54115",
        //        "quantity": "0.001",
        //        "stop_price": "0",
        //        "trade_id": "0",
        //        "trade_price": "0",
        //        "trade_quantity": "0",
        //        "trade_type": ""
        //    },
        //
        let mut id: Value = self.safe_string_2(order.clone(), Value::from("order_id"), Value::from("parent_order_id"), Value::Undefined);
        let mut event_time: Value = self.safe_integer_product_2(order.clone(), Value::from("event_time"), Value::from("created"), Value::from(0.000001), Value::Undefined);
        let mut timestamp: Value = self.safe_timestamp(order.clone(), Value::from("created"), event_time.clone());
        let mut order_type: Value = self.safe_string_2(order.clone(), Value::from("type"), Value::from("order_type"), Value::Undefined);
        let mut side: Value = <Self as Exmo>::parse_side(self, order_type.clone());
        let mut market_id: Value = Value::Undefined;
        if order.contains_key(Value::from("pair")) {
            market_id = order.get(Value::from("pair"));
        } else if order.contains_key(Value::from("in_currency")) && order.contains_key(Value::from("out_currency")) {
            if side.clone() == Value::from("buy") {
                market_id = order.get(Value::from("in_currency")) + Value::from("_") + order.get(Value::from("out_currency"));
            } else {
                market_id = order.get(Value::from("out_currency")) + Value::from("_") + order.get(Value::from("in_currency"));
            };
        };
        market = self.safe_market(market_id.clone(), market.clone(), Value::Undefined, Value::Undefined);
        let mut symbol: Value = market.get(Value::from("symbol"));
        let mut amount: Value = self.safe_string(order.clone(), Value::from("quantity"), Value::Undefined);
        if amount.clone().is_nullish() {
            let mut amount_field: Value = if side.clone() == Value::from("buy") { Value::from("in_amount") } else { Value::from("out_amount") };
            amount = self.safe_string(order.clone(), amount_field.clone(), Value::Undefined);
        };
        let mut price: Value = self.safe_string(order.clone(), Value::from("price"), Value::Undefined);
        let mut cost: Value = self.safe_string(order.clone(), Value::from("amount"), Value::Undefined);
        let mut transactions: Value = self.safe_value(order.clone(), Value::from("trades"), Value::new_array());
        let mut client_order_id: Value = self.safe_integer(order.clone(), Value::from("client_id"), Value::Undefined);
        let mut trigger_price: Value = self.safe_string(order.clone(), Value::from("stop_price"), Value::Undefined);
        if trigger_price.clone() == Value::from("0") {
            trigger_price = Value::Undefined;
        };
        let mut r#type: Value = Value::Undefined;
        if order_type.clone() != Value::from("buy") && order_type.clone() != Value::from("sell") {
            r#type = order_type.clone();
        };
        return self.safe_order(Value::Json(normalize(&Value::Json(json!({
            "id": id,
            "clientOrderId": client_order_id,
            "datetime": self.iso8601(timestamp.clone()),
            "timestamp": timestamp,
            "lastTradeTimestamp": self.safe_integer_product(order.clone(), Value::from("updated"), Value::from(0.000001), Value::Undefined),
            "status": <Self as Exmo>::parse_status(self, self.safe_string(order.clone(), Value::from("order_status"), Value::Undefined)),
            "symbol": symbol,
            "type": r#type,
            "timeInForce": Value::Undefined,
            "postOnly": Value::Undefined,
            "side": side,
            "price": price,
            "triggerPrice": trigger_price,
            "cost": cost,
            "amount": amount,
            "filled": Value::Undefined,
            "remaining": Value::Undefined,
            "average": Value::Undefined,
            "trades": transactions,
            "fee": Value::Undefined,
            "info": order
        }))).unwrap()), market.clone());
    }

