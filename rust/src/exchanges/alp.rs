    fn parse_order(&mut self, mut order: Value, mut market: Value) -> Value {
        //
        // fetchClosedOrders / fetchOrder
        //     {
        //       "id": "923763073",
        //       "date": "1635451090368",
        //       "type": "sell",
        //       "pair": "XRP_USDT",
        //       "price": "1.00000000",
        //       "amount": "0.00000000",
        //       "status": "3",
        //       "amount_filled": "10.00000000",
        //       "amount_original": "10.0"
        //       "trades": [],
        //     }
        //
        // createOrder
        //     {
        //       "success": true,
        //       "date": "1635451754.497541",
        //       "type": "sell",
        //       "oid": "923776755",
        //       "price": "1.0",
        //       "amount": "10.0",
        //       "amount_filled": "0.0",
        //       "amount_original": "10.0",
        //       "trades": []
        //     }
        //
        let mut market_id: Value = self.safe_string(order.clone(), Value::from("pair"), Value::Undefined);
        market = self.safe_market(market_id.clone(), market.clone(), Value::from("_"), Value::Undefined);
        let mut symbol: Value = market.get(Value::from("symbol"));
        let mut success: Value = self.safe_bool(order.clone(), Value::from("success"), false.into());
        let mut timestamp: Value = Value::Undefined;
        if success.is_truthy() {
            timestamp = self.safe_timestamp(order.clone(), Value::from("date"), Value::Undefined);
        } else {
            timestamp = self.safe_integer(order.clone(), Value::from("date"), Value::Undefined);
        };
        let mut price: Value = self.safe_string(order.clone(), Value::from("price"), Value::Undefined);
        let mut remaining: Value = self.safe_string(order.clone(), Value::from("amount"), Value::Undefined);
        let mut filled: Value = self.safe_string(order.clone(), Value::from("amount_filled"), Value::Undefined);
        let mut amount: Value = self.safe_string(order.clone(), Value::from("amount_original"), Value::Undefined);
        let mut status: Value = <Self as Alp>::parse_order_status(self, self.safe_string(order.clone(), Value::from("status"), Value::Undefined));
        let mut id: Value = self.safe_string_n(order.clone(), Value::Json(serde_json::Value::Array(vec![Value::from("oid").into(), Value::from("id").into(), Value::from("order").into()])), Value::Undefined);
        let mut trades: Value = self.safe_value(order.clone(), Value::from("trades"), Value::Undefined);
        let mut side: Value = self.safe_string_2(order.clone(), Value::from("my_side"), Value::from("type"), Value::Undefined);
        return self.safe_order(Value::Json(normalize(&Value::Json(json!({
            "id": id,
            "clientOrderId": Value::Undefined,
            "datetime": self.iso8601(timestamp.clone()),
            "timestamp": timestamp,
            "status": status,
            "symbol": symbol,
            "type": "limit",
            "timeInForce": Value::Undefined,
            "postOnly": Value::Undefined,
            "side": side,
            "price": price,
            "triggerPrice": Value::Undefined,
            "cost": Value::Undefined,
            "amount": amount,
            "filled": filled,
            "remaining": remaining,
            "trades": trades,
            "fee": Value::Undefined,
            "info": order,
            "lastTradeTimestamp": Value::Undefined,
            "average": Value::Undefined
        }))).unwrap()), market.clone());
    }

    async fn create_order(&mut self, mut symbol: Value, mut r#type: Value, mut side: Value, mut amount: Value, mut price: Value, mut params: Value) -> Value {
        params = params.or_default(Value::new_object());
        if r#type.clone() == Value::from("market") {
            panic!(r###"InvalidOrder::new(self.get("id".into()) + Value::from(" only limits orders are supported"))"###);
        };
        self.load_markets(Value::Undefined, Value::Undefined).await;
        let mut market: Value = self.market(symbol.clone());
        let mut request: Value = Value::Json(normalize(&Value::Json(json!({
            "pair": market.get(Value::from("id")),
            "type": side,
            "amount": amount,
            "price": self.price_to_precision(symbol.clone(), price.clone())
        }))).unwrap());
        let mut response: Value = self.dispatch("privatePostOrder".into(), extend_2(request.clone(), params.clone()), Value::Undefined).await;
        if !response.get(Value::from("success")).is_truthy() {
            panic!(r###"InvalidOrder::new(self.get("id".into()) + Value::from(" ") + self.json(response.clone()))"###);
        };
        let mut order: Value = <Self as Alp>::parse_order(self, response.clone(), market.clone());
        let mut order_amount: Value = order.get(Value::from("amount")).to_string();
        amount = if Precise::string_gt(order_amount.clone(), Value::from("0")) { order.get(Value::from("amount")) } else { amount.clone() };
        order.set("amount".into(), self.parse_number(amount.clone(), Value::Undefined));
        return order.clone();
    }

