    fn parse_trade(&mut self, mut trade: Value, mut market: Value) -> Value {
        //
        // fetchTrades
        //
        //     {
        //         "id": 28457,
        //         "price": "4.00000100",
        //         "qty": "12.00000000",
        //         "time": 1499865549590,  // Actual timestamp of trade
        //         "isBuyerMaker": true,
        //         "isBestMatch": true
        //     }
        //
        // fetchTrades - spot
        //
        //     {
        //         "symbol":"USDCUSDT",
        //         "id":20725156,
        //         "orderId":2880918576,
        //         "origClientOrderId":null,
        //         "price":"0.9996000000000000",
        //         "qty":"100.0000000000000000",
        //         "commission":null,
        //         "commissionAssert":null,
        //         "time":1635558511000,
        //         "isBuyer":false,
        //         "isMaker":false,
        //         "isBestMatch":true
        //     }
        //
        // fetchTrades - future
        //
        //     {
        //         "tradeId":12,
        //         "price":0.9,
        //         "qty":1,
        //         "amount":9,
        //         "contractName":"E-SAND-USDT",
        //         "side":"BUY",
        //         "fee":"0.0018",
        //         "bidId":1558124009467904992,
        //         "askId":1558124043827644908,
        //         "bidUserId":10294,
        //         "askUserId":10467,
        //         "isBuyer":true,
        //         "isMaker":true,
        //         "ctime":1678426306000
        //     }
        //
        let mut timestamp: Value = self.safe_integer_2(trade.clone(), Value::from("ctime"), Value::from("time"), Value::Undefined);
        let mut price_string: Value = self.safe_string(trade.clone(), Value::from("price"), Value::Undefined);
        let mut amount_string: Value = self.safe_string(trade.clone(), Value::from("qty"), Value::Undefined);
        let mut market_id: Value = self.safe_string_2(trade.clone(), Value::from("symbol"), Value::from("contractName"), Value::Undefined);
        let mut symbol: Value = self.safe_symbol(market_id.clone(), market.clone(), Value::Undefined, Value::Undefined);
        let mut order_id: Value = self.safe_string(trade.clone(), Value::from("orderId"), Value::Undefined);
        let mut id: Value = self.safe_string_2(trade.clone(), Value::from("id"), Value::from("tradeId"), Value::Undefined);
        let mut side: Value = Value::Undefined;
        let mut buyer_maker: Value = self.safe_bool(trade.clone(), Value::from("isBuyerMaker"), Value::Undefined);
        // ignore "m" until Bitrue fixes api
        let mut is_buyer: Value = self.safe_bool(trade.clone(), Value::from("isBuyer"), Value::Undefined);
        if buyer_maker.clone().is_nonnullish() {
            side = if buyer_maker.is_truthy() { Value::from("sell") } else { Value::from("buy") };
        };
        if is_buyer.clone().is_nonnullish() {
            side = if is_buyer.is_truthy() { Value::from("buy") } else { Value::from("sell") };
        };
        // this is a true side
        let mut fee: Value = Value::Undefined;
        if trade.contains_key(Value::from("commission")) {
            fee = Value::Json(normalize(&Value::Json(json!({
                "cost": self.safe_string_2(trade.clone(), Value::from("commission"), Value::from("fee"), Value::Undefined),
                "currency": self.safe_currency_code(self.safe_string(trade.clone(), Value::from("commissionAssert"), Value::Undefined), Value::Undefined)
            }))).unwrap());
        };
        let mut taker_or_maker: Value = Value::Undefined;
        let mut is_maker: Value = self.safe_bool(trade.clone(), Value::from("isMaker"), Value::Undefined);
        if is_maker.clone().is_nonnullish() {
            taker_or_maker = if is_maker.is_truthy() { Value::from("maker") } else { Value::from("taker") };
        };
        return self.safe_trade(Value::Json(normalize(&Value::Json(json!({
            "info": trade,
            "timestamp": timestamp,
            "datetime": self.iso8601(timestamp.clone()),
            "symbol": symbol,
            "id": id,
            "order": order_id,
            "type": Value::Undefined,
            "side": side,
            "takerOrMaker": taker_or_maker,
            "price": price_string,
            "amount": amount_string,
            "cost": Value::Undefined,
            "fee": fee
        }))).unwrap()), market.clone());
    }

