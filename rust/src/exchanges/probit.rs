    async fn withdraw(&mut self, mut code: Value, mut amount: Value, mut address: Value, mut tag: Value, mut params: Value) -> Value {
        params = params.or_default(Value::new_object());
        (tag, params) = shift_2(self.handle_withdraw_tag_and_params(tag.clone(), params.clone()));
        // In order to use this method
        // you need to allow API withdrawal from the API Settings Page, and
        // and register the list of withdrawal addresses and destination tags on the API Settings page
        // you can only withdraw to the registered addresses using the API
        self.check_address(address.clone());
        self.load_markets(Value::Undefined, Value::Undefined).await;
        let mut currency: Value = self.currency(code.clone());
        if tag.clone().is_nullish() {
            tag = Value::from("");
        };
        let mut request: Value = Value::Json(normalize(&Value::Json(json!({
            "currency_id": currency.get(Value::from("id")),
            "address": address,
            "destination_tag": tag,
            "amount": self.number_to_string(amount.clone())
        }))).unwrap());
        // 'platform_id': 'ETH', // if omitted it will use the default platform for the currency
        // which currency to pay the withdrawal fees
        // only applicable for currencies that accepts multiple withdrawal fee options
        // 'fee_currency_id': 'ETH', // if omitted it will use the default fee policy for each currency
        // whether the amount field includes fees
        // 'include_fee': false, // makes sense only when fee_currency_id is equal to currency_id
        let mut networks: Value = self.safe_value(self.get("options".into()), Value::from("networks"), Value::new_object());
        let mut network: Value = self.safe_string_upper(params.clone(), Value::from("network"), Value::Undefined);
        // this line allows the user to specify either ERC20 or ETH
        network = self.safe_string(networks.clone(), network.clone(), network.clone());
        // handle ERC20>ETH alias
        if network.clone().is_nonnullish() {
            request.set("platform_id".into(), network.clone());
            params = self.omit(params.clone(), Value::from("network"));
        };
        let mut response: Value = self.dispatch("privatePostWithdrawal".into(), extend_2(request.clone(), params.clone()), Value::Undefined).await;
        let mut data: Value = self.safe_dict(response.clone(), Value::from("data"), Value::Undefined);
        return <Self as Probit>::parse_transaction(self, data.clone(), currency.clone());
    }

