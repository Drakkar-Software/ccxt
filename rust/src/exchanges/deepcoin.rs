    fn set_markets(&mut self, mut markets: Value, mut currencies: Value) -> Value {
        markets = Exchange::set_markets(self, markets.clone(), currencies.clone());
        let mut symbols: Value = markets.clone().keys();
        let mut i: usize = 0;
        while i < symbols.len() {
            let mut symbol: Value = symbols.get(i.into());
            let mut market: Value = markets.get(symbol.clone().clone());
            if market.get(Value::from("swap")).is_truthy() {
                let mut additional_id: Value = market.get(Value::from("baseId")) + market.get(Value::from("quoteId"));
                self.get("markets_by_id".into()).set(additional_id.clone(), Value::Json(serde_json::Value::Array(vec![(market.clone()).into()])));
            };
            i += 1;
        };
        // some endpoints return swap market id as base+quote
        return self.get("markets".into());
    }

