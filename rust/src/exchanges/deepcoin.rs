    /// * `[params.reduceOnly]` {bool} - a mark to reduce the position size for margin and swap orders
    /// * `[params.stopLossPrice]` {float} - the price that a stop loss order is triggered at
    /// * `[params.takeProfitPrice]` {float} - the price that a take profit order is triggered at
